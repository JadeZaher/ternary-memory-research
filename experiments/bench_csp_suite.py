"""
experiments/bench_csp_suite.py: Constraint-Satisfaction Suite for FlowTrit, matched arms x seeds.

Protocol bug fixed here: training previously built x_t = (1-t)*noise + t*x_clean, leaking the full
solution through x_t while inference only ever supplies x_t = 0.2*noise + 0.8*c (clues only). A probe
found the shipped 4x4 model at 75.6% solve rate as evaluated, 100% with training-style x_t, 90% with
x_t=0. leak_free=True (default) builds x_t from c during training so train and test match.

Tasks: sudoku4 (MiniSudoku4x4, L=16, V=4, boxes+rows+cols), latin5 (L=25, V=5, rows+cols only),
latin6 (L=36, V=6, rows+cols only). Latin squares are generated by permuting the rows, columns, and
symbol labels of the cyclic square independently and randomly (isotopy-class sampling; duplicates
across the 2000/3000 draws are astronomically unlikely and are not de-duplicated).

Model capacity (d_model=128, n_layers=4, n_heads=4) is held FIXED across all three tasks on purpose:
the suite measures how well a constant-capacity recurrent flow denoiser scales with problem size and
clue sparsity, not how much capacity is needed to saturate each task.

Data generation and the train/test board split use a fixed internal DATA_SEED, independent of
--seeds: every seed in a task trains/evaluates against the same board pool. --seeds only varies model
initialization, FPF batch sampling, and the draw of eval puzzles (fresh clue positions per seed).
"""

import argparse
import copy
import datetime
import json
import os
import random
import sys
import time
from pathlib import Path
from typing import Callable, Dict, List, Optional, Tuple

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import torch
import torch.nn.functional as F

from experiments.flowtrit_model import FlowTritDenoiser
from experiments.test_flowtrit import MiniSudoku4x4

DEVICE = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
DATA_SEED = 20260916  # fixed: board/Latin-square generation and train/test split, independent of --seeds

TIERS_ORDER = ["easy", "medium", "hard"]

TASK_SPECS = {
    "sudoku4": {"seq_len": 16, "num_classes": 4, "tiers": {"easy": 10, "medium": 8, "hard": 6}},
    "latin5": {"seq_len": 25, "num_classes": 5, "tiers": {"easy": 14, "medium": 11, "hard": 8}, "n_generate": 2000},
    "latin6": {"seq_len": 36, "num_classes": 6, "tiers": {"easy": 20, "medium": 16, "hard": 12}, "n_generate": 3000},
}

DEFAULT_SEEDS = {"sudoku4": [1, 2, 3], "latin5": [1, 2, 3], "latin6": [1, 2]}

BATCH_SIZE = 64
LR = 2e-3
WEIGHT_DECAY = 1e-4
MAX_ROLLOUT_K = 4
D_MODEL, N_LAYERS, N_HEADS = 128, 4, 4


def measured(value) -> Dict[str, object]:
    return {"value": value, "label": "measured"}


def derived(value) -> Dict[str, object]:
    return {"value": value, "label": "derived"}


def set_all_seeds(seed: int) -> None:
    random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def mean_std(vals: List[float]) -> Tuple[float, float]:
    if not vals:
        return 0.0, 0.0
    m = sum(vals) / len(vals)
    var = sum((v - m) ** 2 for v in vals) / len(vals)
    return round(m, 4), round(var ** 0.5, 4)


# ==============================================================================
# Latin square generation (latin5, latin6)
# ==============================================================================

def _cyclic_latin_square(n: int) -> List[List[int]]:
    """Base isotopy-class representative: L[r][c] = (r + c) mod n."""
    return [[(r + c) % n for c in range(n)] for r in range(n)]


def _random_latin_square(n: int, rng: random.Random) -> List[int]:
    """Permutes rows, columns, and symbols of the cyclic square independently; returns flat length-n^2 list."""
    base = _cyclic_latin_square(n)
    row_perm = list(range(n))
    col_perm = list(range(n))
    sym_perm = list(range(n))
    rng.shuffle(row_perm)
    rng.shuffle(col_perm)
    rng.shuffle(sym_perm)
    flat = [0] * (n * n)
    for r in range(n):
        for c in range(n):
            flat[r * n + c] = sym_perm[base[row_perm[r]][col_perm[c]]]
    return flat


def is_valid_latin_solution(flat: List[int], n: int) -> bool:
    """Every row and column must be a permutation of 0..n-1 (no box constraint)."""
    if len(flat) != n * n:
        return False
    for r in range(n):
        row = flat[r * n:(r + 1) * n]
        if len(set(row)) != n:
            return False
    for c in range(n):
        col = [flat[r * n + c] for r in range(n)]
        if len(set(col)) != n:
            return False
    return True


def check_clue_adherence(pred: List[int], clues: Dict[int, int]) -> bool:
    return all(pred[idx] == val for idx, val in clues.items())


# ==============================================================================
# Dataset construction
# ==============================================================================

def build_dataset(task_name: str) -> Tuple[List[List[int]], List[List[int]], Callable[[List[int]], bool]]:
    """Returns (train_boards, test_boards, is_valid_solution_fn); split via DATA_SEED only."""
    spec = TASK_SPECS[task_name]
    if task_name == "sudoku4":
        all_boards = MiniSudoku4x4.enumerate_all_boards()  # exactly 288, deterministic enumeration
        rng = random.Random(DATA_SEED)
        shuffled = list(all_boards)
        rng.shuffle(shuffled)
        train_boards = shuffled[:220]
        test_boards = shuffled[220:]
        return train_boards, test_boards, MiniSudoku4x4.is_valid_solution

    n = spec["num_classes"]
    n_generate = spec["n_generate"]
    gen_rng = random.Random(DATA_SEED + n)
    squares = [_random_latin_square(n, gen_rng) for _ in range(n_generate)]
    split_rng = random.Random(DATA_SEED + n + 1)
    shuffled = list(squares)
    split_rng.shuffle(shuffled)
    n_test = int(round(len(shuffled) * 0.3))
    test_boards = shuffled[:n_test]
    train_boards = shuffled[n_test:]
    is_valid_fn = lambda flat, n=n: is_valid_latin_solution(flat, n)
    return train_boards, test_boards, is_valid_fn


def build_eval_puzzles(
    test_boards: List[List[int]],
    seq_len: int,
    tiers: Dict[str, int],
    puzzles_per_tier: int,
    rng: random.Random,
) -> List[Dict[str, object]]:
    """Draws puzzles_per_tier puzzles per tier from held-out boards with fresh clue positions."""
    puzzles = []
    for tier_name in TIERS_ORDER:
        n_clues = tiers[tier_name]
        for _ in range(puzzles_per_tier):
            board = rng.choice(test_boards)
            clue_idxs = rng.sample(range(seq_len), n_clues)
            puzzles.append({"board": board, "clues": {i: board[i] for i in clue_idxs}, "tier": tier_name})
    return puzzles


# ==============================================================================
# Training and evaluation
# ==============================================================================

def train_arm(
    seq_len: int,
    num_classes: int,
    train_boards: List[List[int]],
    ternary: bool,
    leak_free: bool,
    steps: int,
    hard_count: int,
    easy_count: int,
) -> Tuple[FlowTritDenoiser, float]:
    """Batched FPF training; clue count per sample ~ Uniform[hard_count, easy_count]."""
    model = FlowTritDenoiser(
        seq_len=seq_len, num_classes=num_classes, d_model=D_MODEL, n_layers=N_LAYERS, n_heads=N_HEADS, ternary=ternary
    ).to(DEVICE)
    optimizer = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=WEIGHT_DECAY)

    t0 = time.time()
    for _ in range(steps):
        batch_samples = random.choices(train_boards, k=BATCH_SIZE)
        target_indices = torch.tensor(batch_samples, dtype=torch.long, device=DEVICE)
        x_clean = F.one_hot(target_indices, num_classes=num_classes).float()

        clue_mask = torch.zeros(BATCH_SIZE, seq_len, 1, device=DEVICE)
        for i in range(BATCH_SIZE):
            n_clues = random.randint(hard_count, easy_count)
            idxs = random.sample(range(seq_len), n_clues)
            clue_mask[i, idxs, 0] = 1.0
        c = x_clean * clue_mask

        model.train_fpf_step(
            x_clean=x_clean,
            target_indices=target_indices,
            clue_mask=clue_mask,
            c=c,
            optimizer=optimizer,
            max_rollout_k=MAX_ROLLOUT_K,
            leak_free=leak_free,
        )
    return model, time.time() - t0


def evaluate_arm(
    model: FlowTritDenoiser,
    eval_puzzles: List[Dict[str, object]],
    seq_len: int,
    num_classes: int,
    is_valid_fn: Callable[[List[int]], bool],
    max_steps: int,
    early_exit: bool,
    eps_exit: float,
) -> Tuple[Dict[str, float], Dict[str, Dict[str, float]]]:
    """Inference convention: t=0.8, x_t = 0.2*noise + 0.8*c (see rollout_inference)."""
    model.eval()
    tier_stats = {t: {"total": 0, "solved": 0, "steps": 0} for t in TIERS_ORDER}

    with torch.no_grad():
        for puzzle in eval_puzzles:
            board, clues, tier = puzzle["board"], puzzle["clues"], puzzle["tier"]
            target = torch.tensor(board, dtype=torch.long, device=DEVICE).unsqueeze(0)
            x_clean = F.one_hot(target, num_classes=num_classes).float()
            clue_mask = torch.zeros(1, seq_len, 1, device=DEVICE)
            idxs = list(clues.keys())
            clue_mask[0, idxs, 0] = 1.0
            c = x_clean * clue_mask

            t_tensor = torch.tensor([[0.8]], device=DEVICE)
            noise = torch.randn_like(x_clean)
            x_t = 0.2 * noise + 0.8 * c

            result = model.rollout_inference(
                x_t=x_t, c=c, t=t_tensor, clue_mask=clue_mask,
                max_steps=max_steps, early_exit=early_exit, eps_exit=eps_exit,
            )
            pred = result["predictions"].squeeze(0).tolist()
            solved = is_valid_fn(pred) and check_clue_adherence(pred, clues)

            tier_stats[tier]["total"] += 1
            if solved:
                tier_stats[tier]["solved"] += 1
            tier_stats[tier]["steps"] += result["steps_taken"]

    tier_summary = {}
    total_solved = total_count = total_steps = 0
    for tier, d in tier_stats.items():
        cnt = d["total"]
        tier_summary[tier] = {
            "solve_rate": round(d["solved"] / cnt, 4) if cnt else 0.0,
            "mean_steps": round(d["steps"] / cnt, 3) if cnt else 0.0,
        }
        total_solved += d["solved"]
        total_count += cnt
        total_steps += d["steps"]

    overall = {
        "solve_rate": round(total_solved / total_count, 4) if total_count else 0.0,
        "mean_steps": round(total_steps / total_count, 3) if total_count else 0.0,
    }
    return overall, tier_summary


# ==============================================================================
# Per-task orchestration
# ==============================================================================

def run_task(task_name: str, seeds: List[int], steps: int, puzzles_per_tier: int) -> Dict[str, object]:
    spec = TASK_SPECS[task_name]
    seq_len, num_classes = spec["seq_len"], spec["num_classes"]
    tiers = spec["tiers"]
    hard_count, easy_count = tiers["hard"], tiers["easy"]

    train_boards, test_boards, is_valid_fn = build_dataset(task_name)

    arms = ["fp32", "posthoc", "native_ternary"]
    if task_name == "sudoku4":
        arms.append("native_ternary_legacy_leak")

    arm_results = {
        arm: {
            "train_seconds": {"per_seed": []},
            "fixed_k5": {"per_seed": []},
            "dynamic_exit": {"per_seed": []},
        }
        for arm in arms
    }

    for seed in seeds:
        print(f"  [seed {seed}] building eval puzzle set ({puzzles_per_tier}/tier)...")
        puzzle_rng = random.Random(seed * 1_000_003 + (sum(map(ord, task_name)) % 97))
        eval_puzzles = build_eval_puzzles(test_boards, seq_len, tiers, puzzles_per_tier, puzzle_rng)

        fp32_model = None
        for arm in arms:
            set_all_seeds(seed)
            if arm == "fp32":
                model, train_s = train_arm(seq_len, num_classes, train_boards, ternary=False, leak_free=True,
                                            steps=steps, hard_count=hard_count, easy_count=easy_count)
                fp32_model = model
            elif arm == "posthoc":
                model = copy.deepcopy(fp32_model)
                model.ternarize_post_hoc(threshold_ratio=0.75)
                train_s = 0.0  # reuses fp32 weights; only a deepcopy + threshold pass, no training
            elif arm == "native_ternary":
                model, train_s = train_arm(seq_len, num_classes, train_boards, ternary=True, leak_free=True,
                                            steps=steps, hard_count=hard_count, easy_count=easy_count)
            else:  # native_ternary_legacy_leak
                model, train_s = train_arm(seq_len, num_classes, train_boards, ternary=True, leak_free=False,
                                            steps=steps, hard_count=hard_count, easy_count=easy_count)

            print(f"    [seed {seed}] arm={arm} trained in {train_s:.2f}s (measured)")
            arm_results[arm]["train_seconds"]["per_seed"].append(round(train_s, 3))

            overall_fixed, tier_fixed = evaluate_arm(model, eval_puzzles, seq_len, num_classes, is_valid_fn,
                                                      max_steps=5, early_exit=False, eps_exit=0.03)
            overall_dyn, tier_dyn = evaluate_arm(model, eval_puzzles, seq_len, num_classes, is_valid_fn,
                                                  max_steps=6, early_exit=True, eps_exit=0.03)
            print(f"    [seed {seed}] arm={arm} fixed_k5 solve_rate={overall_fixed['solve_rate']*100:.1f}% "
                  f"dynamic solve_rate={overall_dyn['solve_rate']*100:.1f}% dynamic mean_steps={overall_dyn['mean_steps']:.2f}")

            arm_results[arm]["fixed_k5"]["per_seed"].append({"seed": seed, "overall": overall_fixed, "tiers": tier_fixed})
            arm_results[arm]["dynamic_exit"]["per_seed"].append({"seed": seed, "overall": overall_dyn, "tiers": tier_dyn})

    for arm in arms:
        ts = arm_results[arm]["train_seconds"]["per_seed"]
        m, s = mean_std(ts)
        arm_results[arm]["train_seconds"]["mean"] = m
        arm_results[arm]["train_seconds"]["std"] = s

        for mode in ("fixed_k5", "dynamic_exit"):
            per_seed = arm_results[arm][mode]["per_seed"]
            solve_rates = [p["overall"]["solve_rate"] for p in per_seed]
            steps_vals = [p["overall"]["mean_steps"] for p in per_seed]
            m_sr, s_sr = mean_std(solve_rates)
            m_st, s_st = mean_std(steps_vals)
            arm_results[arm][mode]["mean_solve_rate"] = m_sr
            arm_results[arm][mode]["std_solve_rate"] = s_sr
            arm_results[arm][mode]["mean_steps"] = m_st
            arm_results[arm][mode]["std_steps"] = s_st

            tier_means = {}
            for tier in TIERS_ORDER:
                tier_sr = [p["tiers"][tier]["solve_rate"] for p in per_seed]
                tier_st = [p["tiers"][tier]["mean_steps"] for p in per_seed]
                m1, s1 = mean_std(tier_sr)
                m2, s2 = mean_std(tier_st)
                tier_means[tier] = {"mean_solve_rate": m1, "std_solve_rate": s1, "mean_steps": m2, "std_steps": s2}
            arm_results[arm][mode]["tier_means"] = tier_means

    findings = {
        "native_minus_posthoc_solve_rate": round(
            arm_results["native_ternary"]["fixed_k5"]["mean_solve_rate"]
            - arm_results["posthoc"]["fixed_k5"]["mean_solve_rate"], 4),
        "native_minus_fp32_solve_rate": round(
            arm_results["native_ternary"]["fixed_k5"]["mean_solve_rate"]
            - arm_results["fp32"]["fixed_k5"]["mean_solve_rate"], 4),
        "dynamic_exit_step_reduction_pct": round(
            (1.0 - arm_results["native_ternary"]["dynamic_exit"]["mean_steps"] / 5.0) * 100.0, 2),
        "dynamic_exit_minus_fixed_solve_rate": round(
            arm_results["native_ternary"]["dynamic_exit"]["mean_solve_rate"]
            - arm_results["native_ternary"]["fixed_k5"]["mean_solve_rate"], 4),
    }
    if task_name == "sudoku4":
        findings["leak_free_minus_legacy_solve_rate"] = round(
            arm_results["native_ternary"]["fixed_k5"]["mean_solve_rate"]
            - arm_results["native_ternary_legacy_leak"]["fixed_k5"]["mean_solve_rate"], 4)

    return {
        "seq_len": seq_len,
        "num_classes": num_classes,
        "tiers": tiers,
        "train_boards_count": len(train_boards),
        "test_boards_count": len(test_boards),
        "seeds_used": seeds,
        "chance_cell_accuracy_pct": derived(round(100.0 / num_classes, 4)),
        "arms": arm_results,
        "findings": findings,
    }


def run_suite(tasks: List[str], seeds_override: Optional[List[int]], steps: int, puzzles_per_tier: int) -> Dict[str, object]:
    results = {}
    seeds_used = {}
    for task_name in tasks:
        seeds = seeds_override if seeds_override is not None else DEFAULT_SEEDS[task_name]
        seeds_used[task_name] = seeds
        print(f"\n{'=' * 80}\nTask: {task_name} | seeds={seeds} | steps={steps} | puzzles/tier={puzzles_per_tier}\n{'=' * 80}")
        results[task_name] = run_task(task_name, seeds, steps, puzzles_per_tier)

    return {
        "status": "COMPLETED",
        "timestamp": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "torch_version": torch.__version__,
        "device": str(DEVICE),
        "config": {
            "tasks": tasks,
            "steps": steps,
            "puzzles_per_tier": puzzles_per_tier,
            "batch_size": BATCH_SIZE,
            "lr": LR,
            "weight_decay": WEIGHT_DECAY,
            "max_rollout_k": MAX_ROLLOUT_K,
            "d_model": D_MODEL,
            "n_layers": N_LAYERS,
            "n_heads": N_HEADS,
        },
        "seeds": seeds_used,
        "tasks": results,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--tasks", type=str, default="sudoku4,latin5,latin6")
    parser.add_argument("--seeds", type=str, default=None, help="comma-separated ints; default is per-task")
    parser.add_argument("--steps", type=int, default=1500)
    parser.add_argument("--puzzles-per-tier", type=int, default=100)
    parser.add_argument("--json", type=str, default="outputs/csp-suite-results.json")
    parser.add_argument("--smoke", action="store_true")
    args = parser.parse_args()

    task_list = [t.strip() for t in args.tasks.split(",") if t.strip()]
    seeds_override = [int(s) for s in args.seeds.split(",")] if args.seeds else None

    if args.smoke:
        task_list = task_list[:1]
        seeds_override = (seeds_override or DEFAULT_SEEDS[task_list[0]])[:1]
        steps = 30
        puzzles_per_tier = 5
    else:
        steps = args.steps
        puzzles_per_tier = args.puzzles_per_tier

    output = run_suite(task_list, seeds_override, steps, puzzles_per_tier)

    out_path = Path(args.json)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2)
    print(f"\nResults written to {out_path.resolve()}")
